/// Render the surface as the fixed-width text table the guard binary prints.
///
/// The rendering is deterministic so a diff of two runs is a diff of the
/// boundary, not of formatting.
pub fn render_surface_table(rows: &[OwnershipRow]) -> String {
    const HEADERS: [&str; 8] = [
        "item",
        "owning crate",
        "arguments",
        "returns",
        "alloc",
        "drop",
        "panic=abort",
        "phase",
    ];

    let mut cells: Vec<[String; 8]> = Vec::with_capacity(rows.len() + 1);
    cells.push(HEADERS.map(str::to_owned));
    for row in rows {
        cells.push([
            row.item.to_owned(),
            row.owning_crate.to_owned(),
            row.argument_types.to_owned(),
            row.return_type.to_owned(),
            row.allocation_owner.label().to_owned(),
            row.drop_owner.label().to_owned(),
            if row.panic_abort { "yes" } else { "no" }.to_owned(),
            row.phase.label().to_owned(),
        ]);
    }

    let mut widths = [0_usize; 8];
    for record in &cells {
        for (column, value) in record.iter().enumerate() {
            widths[column] = widths[column].max(value.chars().count());
        }
    }

    let mut rendered = String::new();
    for record in &cells {
        for (column, value) in record.iter().enumerate() {
            let padding = widths[column] - value.chars().count();
            rendered.push_str(value);
            if column + 1 < record.len() {
                rendered.extend(std::iter::repeat_n(' ', padding + 2));
            }
        }
        rendered.push('\n');
    }
    rendered
}
