//! The generation-1 boundary ownership table.
//!
//! Every item that crosses the host/plugin boundary is enumerated here with the
//! facts a reviewer needs to reason about it without reading the call site:
//! which crate owns the declaration, what it takes and returns, who allocates
//! the returned storage, who drops it, the panic policy in force, and whether
//! it runs at startup or on the request hot path.
//!
//! The table is the machine-readable half of
//! `docs/specs/plugin-api-ownership.md`. The `check-plugin-api-ownership`
//! binary compares the two and fails when a row is missing from the spec, so a
//! new boundary item cannot land undocumented.

/// The precondition that makes every `alloc owner = plugin` /
/// `drop owner = host` row in [`GENERATION_1_SURFACE`] sound.
///
/// Library residency guarantees the drop glue is still mapped when the host
/// runs it; it says nothing about which allocator the free lands in. Rows that
/// transfer plugin-allocated storage to the host therefore additionally require
/// one global allocator across every loaded artifact. This constant is the
/// stated rule, not its enforcement: the loader that checks it lands with the
/// allocator provider.
pub const SHARED_ALLOCATOR_PRECONDITION: &str = "\
Every boundary row with alloc_owner = plugin and drop_owner = host requires \
that the host binary and every plugin cdylib link the same allocator. The \
aiperf binary installs mimalloc through aiperf-allocator-provider; a plugin \
must declare the same provider as its #[global_allocator] before the host \
loads it. A cdylib that allocates from a different allocator produces heap \
corruption when the host drops the transferred value, because the free is \
issued to an allocator that never owned the block.";

/// Who allocates or drops the storage a boundary item names.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum StorageOwner {
    /// The plugin library allocates or drops it. Plugin libraries stay resident
    /// for the whole process, so plugin-owned storage outlives every host value
    /// derived from it.
    Plugin,
    /// The host allocates or drops it.
    Host,
    /// The item transfers no storage: it borrows, copies, or returns a unit.
    None,
}

impl StorageOwner {
    /// The lowercase label used in the spec table.
    pub const fn label(&self) -> &'static str {
        match self {
            Self::Plugin => "plugin",
            Self::Host => "host",
            Self::None => "none",
        }
    }
}

/// When a boundary item is called relative to a benchmark run.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CallPhase {
    /// Called during load, registration, and plan validation, before any
    /// request is issued.
    Startup,
    /// Called per request or per token while a phase is running.
    HotPath,
}

impl CallPhase {
    /// The lowercase label used in the spec table.
    pub const fn label(&self) -> &'static str {
        match self {
            Self::Startup => "startup",
            Self::HotPath => "hot-path",
        }
    }
}

/// One boundary item and the ownership facts that govern it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OwnershipRow {
    /// Fully qualified path of the item, exactly as the spec table names it.
    pub item: &'static str,
    /// The crate whose source declares the item.
    pub owning_crate: &'static str,
    /// Argument types in declaration order, or `()` for none.
    pub argument_types: &'static str,
    /// Return type, or `()`.
    pub return_type: &'static str,
    /// Who allocates the storage the item yields.
    pub allocation_owner: StorageOwner,
    /// Who drops that storage.
    pub drop_owner: StorageOwner,
    /// Whether the item is compiled under `panic = abort`.
    pub panic_abort: bool,
    /// When the item is called.
    pub phase: CallPhase,
}

