    /// Drain one decoder into `(record_id, content)` pairs.
    async fn drain(
        decoder: &mut dyn StreamingPartitionDecoder,
        max_fragments: usize,
    ) -> Vec<(crate::streaming::identity::StableRecordId, Vec<u8>)> {
        let mut collected = Vec::new();
        loop {
            let step = decoder
                .next_batch(DecodeBatchBudget {
                    max_fragments,
                    max_bytes: 1 << 20,
                })
                .await
                .expect("decode step");
            match step {
                DecodeStep::Batch(batch) => {
                    assert!(!batch.fragments.is_empty(), "a batch is never empty");
                    assert!(batch.fragments.len() <= max_fragments);
                    for fragment in &batch.fragments {
                        collected.push((fragment.record_id, turn_content(fragment)));
                    }
                }
                DecodeStep::End(_) => return collected,
            }
        }
    }

