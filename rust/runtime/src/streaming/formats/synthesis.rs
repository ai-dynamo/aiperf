//! Deterministic synthetic-prompt streaming format.
//!
//! A synthetic dataset has no bytes to decode. Each immutable partition holds a
//! small canonical shard manifest naming a shard index, a record count, and a
//! seed; every semantic input — corpus, tokenizer, input length, prefix reuse —
//! is frozen in this format's own validated configuration and folded into one
//! plan digest before a fragment is generated.
//!
//! Content is a pure function of `(plan_digest, shard_index, record_ordinal)`,
//! so a decoder resumed at an exact record ordinal emits byte-identical
//! fragments. The checkpoint therefore retains only the fixed-width cursor and
//! never any generated content.
//!
//! The immutable object is the authority for *how many* records and *which*
//! seed; the frozen plan digest is the authority for content. A resumed cursor
//! whose plan digest disagrees with the recomputed plan is a terminal
//! [`DecodeFailureCode::SynthesisAuthorityMismatch`], never a quarantine: the
//! same record identities would otherwise name different content.

