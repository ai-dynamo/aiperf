/// Stateful model-name selection policy.
pub trait ModelSelector {
    /// Select the model for the next turn.
    fn next(&mut self) -> ModelId;
}

/// Factory seam that gives each composition run fresh selector state.
pub trait ModelSelectorFactory: Send + Sync {
    /// Construct a selector over a validated non-empty model list.
    fn create(&self, models: &[ModelId], root: RngRoot) -> Result<Box<dyn ModelSelector>>;
}

/// Storage policy for synthetic prompt material generated by trace composers.
///
/// Online transports need text/token segments to build request bodies. Simulator
/// transports that consume source-native hash identities can retain only the
/// authored token count and the `TraceHashIds` segment instead.
pub trait TracePromptStoragePolicy: Send + Sync {
    /// Whether a trace row with these source hash identities stores generated prompt material.
    fn stores_generated_prompt(&self, hash_ids: &[i64]) -> bool;
}

/// Retain generated text/token segments for every trace row.
#[derive(Debug, Clone, Copy, Default)]
pub struct MaterializedTracePromptStorage;

impl TracePromptStoragePolicy for MaterializedTracePromptStorage {
    fn stores_generated_prompt(&self, _hash_ids: &[i64]) -> bool {
        true
    }
}

/// Retain generated prompts only when a trace row has no source hash identity.
#[derive(Debug, Clone, Copy, Default)]
pub struct HashIdentityTracePromptStorage;

impl TracePromptStoragePolicy for HashIdentityTracePromptStorage {
    fn stores_generated_prompt(&self, hash_ids: &[i64]) -> bool {
        hash_ids.is_empty()
    }
}

/// Round-robin model selector factory.
#[derive(Debug, Clone, Copy, Default)]
pub struct RoundRobinModelSelectorFactory;

struct RoundRobinModelSelector {
    models: Vec<ModelId>,
    index: usize,
}

impl ModelSelector for RoundRobinModelSelector {
    fn next(&mut self) -> ModelId {
        let model = self.models[self.index].clone();
        self.index = (self.index + 1) % self.models.len();
        model
    }
}

impl ModelSelectorFactory for RoundRobinModelSelectorFactory {
    fn create(&self, models: &[ModelId], _root: RngRoot) -> Result<Box<dyn ModelSelector>> {
        if models.is_empty() {
            return Err(DatasetError::Validation(
                "model selection requires at least one model".into(),
            ));
        }
        Ok(Box::new(RoundRobinModelSelector {
            models: models.to_vec(),
            index: 0,
        }))
    }
}

/// Uniform-random model selector factory.
#[derive(Debug, Clone, Copy, Default)]
pub struct RandomModelSelectorFactory;

struct RandomModelSelector {
    models: Vec<ModelId>,
    rng: RandomGenerator,
}

impl ModelSelector for RandomModelSelector {
    fn next(&mut self) -> ModelId {
        self.rng
            .choice(&self.models)
            .expect("factory rejects an empty model list")
            .clone()
    }
}

impl ModelSelectorFactory for RandomModelSelectorFactory {
    fn create(&self, models: &[ModelId], root: RngRoot) -> Result<Box<dyn ModelSelector>> {
        if models.is_empty() {
            return Err(DatasetError::Validation(
                "model selection requires at least one model".into(),
            ));
        }
        Ok(Box::new(RandomModelSelector {
            models: models.to_vec(),
            rng: RandomGenerator::from_seed(root.derive_seed("composer.turn.model_selection")),
        }))
    }
}

/// Cross-format composition configuration.
pub struct ComposeConfig {
    /// Run root for order-independent component RNG streams.
    pub rng_root: RngRoot,
    /// Primary and alternate model names.
    pub models: Vec<ModelId>,
    /// Fresh selector factory for this composition pass.
    pub model_selector: Arc<dyn ModelSelectorFactory>,
    /// Fallback output-length distribution; an authored per-row value wins.
    pub output_length_distribution: Option<SamplingDistribution>,
    /// Optional hard cap applied after authored or sampled output length.
    pub max_output_tokens: Option<u32>,
    /// Paired synthetic ISL/OSL distribution.
    pub sequence_length_distribution: Option<SequenceLengthDistribution>,
    /// Full synthetic dataset shape for the `synthetic` and
    /// `synthetic_rankings` composers.
    pub synthetic_config: Option<SyntheticDatasetConfig>,
    /// Optional format-neutral trace synthesis applied by trace composers.
    pub trace_synthesis: Option<TraceSynthesisConfig>,
    /// Injectable image/audio/video generator factory.
    pub media_generator_factory: Arc<dyn SyntheticMediaGeneratorFactory>,
    /// Shared system prompt interned once and referenced by every conversation.
    pub shared_system_prompt: Option<String>,
    /// Per-conversation user context prompts in authored conversation order.
    pub user_context_prompts: Vec<String>,
    /// Context behavior inherited by conversations without an explicit mode.
    pub default_context_mode: ConversationContextMode,
    /// Local/URL/already-encoded media resolution implementation.
    pub media_resolver: Arc<dyn MediaResolver>,
    /// Synthetic prompt generator factory used by trace/synthetic composers.
    pub prompt_generator: Arc<dyn PromptGeneratorFactory>,
    /// Whether hash-backed trace rows retain generated prompt text/token segments.
    pub trace_prompt_storage: Arc<dyn TracePromptStoragePolicy>,
    /// Whether the selected endpoint requires exact token IDs instead of text.
    ///
    /// Loaders use this only to choose the stored prompt representation. Token
    /// validity is established before the segment pool is frozen, so endpoint
    /// adapters never parse or verify authored integer arrays on dispatch.
    pub requires_raw_token_ids: bool,
    /// Format-specific composition settings validated by the selected composer.
    pub format_options: Map<String, Value>,
}

impl ComposeConfig {
    /// Construct the normal single-model, round-robin composition policy.
    pub fn new(model: impl Into<ModelId>, rng_root: RngRoot) -> Self {
        Self {
            rng_root,
            models: vec![model.into()],
            model_selector: Arc::new(RoundRobinModelSelectorFactory),
            output_length_distribution: None,
            max_output_tokens: None,
            sequence_length_distribution: None,
            synthetic_config: None,
            trace_synthesis: None,
            media_generator_factory: Arc::new(NativeSyntheticMediaGeneratorFactory::default()),
            shared_system_prompt: None,
            user_context_prompts: Vec::new(),
            default_context_mode: ConversationContextMode::DeltasWithoutResponses,
            media_resolver: Arc::new(InlineMediaResolver),
            prompt_generator: Arc::new(CorpusPromptGeneratorFactory::default()),
            trace_prompt_storage: Arc::new(MaterializedTracePromptStorage),
            requires_raw_token_ids: false,
            format_options: Map::new(),
        }
    }

    pub(crate) fn state<'a>(
        &'a self,
        tokenizer: &'a dyn TextTokenizer,
        segments: &'a mut SegmentPool,
    ) -> Result<ComposeState<'a>> {
        Ok(ComposeState {
            config: self,
            tokenizer,
            segments,
            finalizer: self.finalizer()?,
        })
    }

    pub(crate) fn finalizer(&self) -> Result<TurnFinalizer<'_>> {
        Ok(TurnFinalizer {
            config: self,
            model_selector: self.model_selector.create(&self.models, self.rng_root)?,
            max_tokens_rng: RandomGenerator::from_seed(
                self.rng_root.derive_seed("composer.turn.max_tokens"),
            ),
        })
    }
}

/// Format-specific conversion from parsed rows to handle-only conversations.
pub trait Composer: Send + Sync {
    /// Compose rows, interning every payload into `segments` in one pass.
    fn compose(
        &self,
        rows: Vec<RawRow>,
        config: &ComposeConfig,
        tokenizer: &dyn TextTokenizer,
        segments: &mut SegmentPool,
    ) -> Result<Vec<Conversation>>;
}

pub(crate) struct ComposeState<'a> {
    pub(crate) config: &'a ComposeConfig,
    pub(crate) tokenizer: &'a dyn TextTokenizer,
    pub(crate) segments: &'a mut SegmentPool,
    finalizer: TurnFinalizer<'a>,
}

impl ComposeState<'_> {
    pub(crate) fn finalize_turn(&mut self, turn: &mut Turn) -> Result<()> {
        self.finalizer.finalize_turn(turn)
    }
}

pub(crate) struct TurnFinalizer<'a> {
    config: &'a ComposeConfig,
    model_selector: Box<dyn ModelSelector>,
    max_tokens_rng: RandomGenerator,
}

impl TurnFinalizer<'_> {
    pub(crate) fn finalize_turn(&mut self, turn: &mut Turn) -> Result<()> {
        if turn.model.is_none() {
            turn.model = Some(self.model_selector.next());
        }
        if turn.max_tokens.is_none()
            && let Some(distribution) = &self.config.output_length_distribution
        {
            let sampled = distribution
                .sample_int(&mut self.max_tokens_rng)
                .map_err(|error| DatasetError::Validation(error.to_string()))?;
            turn.max_tokens = Some(u32::try_from(sampled).map_err(|_| {
                DatasetError::Validation(format!("sampled output length {sampled} exceeds u32"))
            })?);
        }
        if let (Some(value), Some(cap)) = (turn.max_tokens, self.config.max_output_tokens) {
            turn.max_tokens = Some(value.min(cap));
        }
        Ok(())
    }
}

/// Apply shared/per-conversation prompts after a format composer returns. Formats
/// that already injected them are left untouched; newly injected roots rebase the
/// conversation's segment chains so prefix-dependent IDs include the context.
pub(crate) fn apply_common_contexts(
    conversations: &mut [Conversation],
    config: &ComposeConfig,
    tokenizer: &dyn TextTokenizer,
    segments: &mut SegmentPool,
) -> Result<()> {
    if !config.user_context_prompts.is_empty()
        && config.user_context_prompts.len() != conversations.len()
    {
        return Err(DatasetError::Validation(format!(
            "{} user context prompts were provided for {} conversations",
            config.user_context_prompts.len(),
            conversations.len()
        )));
    }
    let system_tokens = config
        .shared_system_prompt
        .as_deref()
        .map(|prompt| tokenizer.encode(prompt))
        .transpose()?;
    for (index, conversation) in conversations.iter_mut().enumerate() {
        let mut injected = false;
        if conversation.system.is_none()
            && let (Some(prompt), Some(tokens)) = (
                config.shared_system_prompt.as_deref(),
                system_tokens.as_ref(),
            )
        {
            conversation.system = Some(segments.intern_text(
                None,
                "system",
                Bytes::copy_from_slice(prompt.as_bytes()),
                tokens.clone().into_boxed_slice(),
            )?);
            injected = true;
        }
        if conversation.user_context.is_none()
            && let Some(prompt) = config.user_context_prompts.get(index)
        {
            conversation.user_context = Some(segments.intern_text(
                conversation.system,
                "user",
                Bytes::copy_from_slice(prompt.as_bytes()),
                tokenizer.encode(prompt)?.into_boxed_slice(),
            )?);
            injected = true;
        }
        if injected {
            let root = conversation.user_context.or(conversation.system);
            let mut remapped = HashMap::new();
            rebase_conversation_handles(conversation, root, segments, &mut remapped)?;
        }
    }
    Ok(())
}

fn rebase_conversation_handles(
    conversation: &mut Conversation,
    root: Option<Handle>,
    segments: &mut SegmentPool,
    remapped: &mut HashMap<Handle, Handle>,
) -> Result<()> {
    for turn in &mut conversation.turns {
        // The unified dispatch body holds the prebuilt raw body, token-native
        // handle, and message handles (segment-unification §9 stage 3); rebase
        // each onto the newly injected context root.
        for handle in &mut turn.body {
            *handle = rebase_handle(*handle, root, segments, remapped)?;
        }
        for group in &mut turn.content {
            for handle in &mut group.handles {
                *handle = rebase_handle(*handle, root, segments, remapped)?;
            }
        }
        for handle in [
            &mut turn.raw_messages,
            &mut turn.tools,
            &mut turn.raw_system,
            &mut turn.extra_body,
            &mut turn.extra_headers,
            &mut turn.request_parameters,
        ] {
            if let Some(value) = *handle {
                *handle = Some(rebase_handle(value, root, segments, remapped)?);
            }
        }
    }
    Ok(())
}

fn rebase_handle(
    handle: Handle,
    root: Option<Handle>,
    segments: &mut SegmentPool,
    remapped: &mut HashMap<Handle, Handle>,
) -> Result<Handle> {
    if let Some(rebased) = remapped.get(&handle) {
        return Ok(*rebased);
    }
    let segment = segments
        .segment(handle)
        .cloned()
        .ok_or(DatasetError::UnknownHandle(handle))?;
    let parent = match segment.parent {
        Some(parent) => Some(rebase_handle(parent, root, segments, remapped)?),
        None => root,
    };
    let rebased = segments.intern(parent, segment.payload)?;
    remapped.insert(handle, rebased);
    Ok(rebased)
}

/// Deterministic counter IDs when a seed exists, UUIDv4 otherwise.
#[derive(Debug, Clone)]
pub struct SessionIdGenerator {
    deterministic: bool,
    prefix: String,
    counter: u64,
}

impl SessionIdGenerator {
    /// Construct a generator; the seed value selects deterministic mode but does
    /// not alter the counter sequence, matching Python AIPerf.
    pub fn new(seed: Option<u64>, prefix: impl Into<String>) -> Self {
        Self {
            deterministic: seed.is_some(),
            prefix: prefix.into(),
            counter: 0,
        }
    }

    /// Generate the next unique identifier.
    pub fn next_id(&mut self) -> SessionId {
        if self.deterministic {
            let id = SessionId::new(format!("{}_{:06}", self.prefix, self.counter));
            self.counter += 1;
            id
        } else {
            SessionId::new(uuid::Uuid::new_v4().to_string())
        }
    }

    /// Reset the deterministic sequence to zero.
    pub fn reset(&mut self) {
        self.counter = 0;
    }

    /// Number of deterministic IDs emitted since construction or reset.
    pub const fn counter(&self) -> u64 {
        self.counter
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn session_ids_match_python_seeded_and_unseeded_contracts() {
        let mut deterministic = SessionIdGenerator::new(Some(99), "session");
        assert_eq!(deterministic.next_id().as_str(), "session_000000");
        assert_eq!(deterministic.next_id().as_str(), "session_000001");
        deterministic.reset();
        assert_eq!(deterministic.next_id().as_str(), "session_000000");

        let mut random = SessionIdGenerator::new(None, "ignored");
        let first = random.next_id();
        let second = random.next_id();
        assert_ne!(first, second);
        assert_eq!(first.as_str().len(), 36);
    }

    #[test]
    fn round_robin_and_random_selectors_have_fresh_reproducible_state() {
        let models = vec![ModelId::from("a"), ModelId::from("b")];
        let mut round = RoundRobinModelSelectorFactory
            .create(&models, RngRoot::new(Some(1)))
            .unwrap();
        assert_eq!(round.next().as_str(), "a");
        assert_eq!(round.next().as_str(), "b");
        assert_eq!(round.next().as_str(), "a");

        let mut first = RandomModelSelectorFactory
            .create(&models, RngRoot::new(Some(7)))
            .unwrap();
        let mut second = RandomModelSelectorFactory
            .create(&models, RngRoot::new(Some(7)))
            .unwrap();
        assert_eq!(
            (0..50).map(|_| first.next()).collect::<Vec<_>>(),
            (0..50).map(|_| second.next()).collect::<Vec<_>>()
        );
    }

    #[test]
    fn common_contexts_rebase_existing_segment_chains_under_the_new_prefix() {
        let tokenizer = crate::dataset::tokenizer::TiktokenTokenizer::builtin();
        let mut segments = SegmentPool::new();
        let prompt = segments
            .intern_text(
                None,
                "user",
                Bytes::from_static(b"prompt"),
                tokenizer.encode("prompt").unwrap().into_boxed_slice(),
            )
            .unwrap();
        let mut conversation = Conversation::new("session");
        conversation.turns.push(Turn {
            content: smallvec::smallvec![crate::dataset::model::ContentGroup {
                kind: crate::dataset::model::MediaKind::Text,
                name: String::new(),
                handles: smallvec::smallvec![prompt],
            }],
            ..Turn::default()
        });
        let mut config = ComposeConfig::new("model", RngRoot::new(Some(1)));
        config.shared_system_prompt = Some("system".into());
        config.user_context_prompts = vec!["context".into()];
        apply_common_contexts(
            std::slice::from_mut(&mut conversation),
            &config,
            &tokenizer,
            &mut segments,
        )
        .unwrap();

        let system = conversation.system.unwrap();
        let context = conversation.user_context.unwrap();
        let rebased_prompt = conversation.turns[0].content[0].handles[0];
        assert_eq!(segments.segment(context).unwrap().parent, Some(system));
        assert_eq!(
            segments.segment(rebased_prompt).unwrap().parent,
            Some(context)
        );
        assert_ne!(prompt, rebased_prompt);
    }
}
